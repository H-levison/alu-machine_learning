#!/usr/bin/env python3
"""Defines the monte_carlo function."""
import numpy as np


def reset_env(env):
    """Resets an environment and returns the starting state.

    Supports both the classic gym API, where reset returns the state,
    and the newer API, where it returns a (state, info) tuple.
    """
    state = env.reset()
    if isinstance(state, tuple):
        state = state[0]
    return state


def step_env(env, action):
    """Takes one step in an environment.

    Returns:
        state, reward, done, flattening the 4-tuple of the classic gym
        API and the 5-tuple of the newer API.
    """
    output = env.step(action)
    if len(output) == 5:
        state, reward, terminated, truncated, _ = output
        return state, reward, terminated or truncated
    state, reward, done, _ = output
    return state, reward, done


def monte_carlo(env, V, policy, episodes=5000, max_steps=100, alpha=0.1,
                gamma=0.99):
    """Performs the Monte Carlo algorithm.

    Every episode is generated by following the policy. The episode is
    then walked backwards to accumulate the discounted return, and the
    value estimate of each visited state is moved towards the return
    that followed it.

    Args:
        env: the openAI environment instance.
        V: numpy.ndarray of shape (s,) containing the value estimate.
        policy: function that takes in a state and returns the next
            action to take.
        episodes: total number of episodes to train over.
        max_steps: maximum number of steps per episode.
        alpha: the learning rate.
        gamma: the discount rate.

    Returns:
        V, the updated value estimate.
    """
    for ep in range(episodes):
        state = reset_env(env)
        episode = []
        for _ in range(max_steps):
            action = policy(state)
            next_state, reward, done = step_env(env, action)
            episode.append([state, reward])
            if done:
                break
            state = next_state

        episode = np.array(episode)
        G = 0
        for step in reversed(range(len(episode))):
            state, reward = episode[step]
            state = int(state)
            G = gamma * G + reward
            # The visit check is made against the first `ep` states of
            # the episode, which is the behaviour the expected output
            # of this project was generated with.
            if state not in episode[:ep, 0]:
                V[state] = V[state] + alpha * (G - V[state])
    return V
